"""
experiment/run_deposit_type_analysis.py

Comment (1)-A / (1)-B: deposit-type heterogeneity diagnostics.

Pure analysis on the already-processed dataset -- no retraining, no new
experiment sweep. Reuses the exact same XGBoost+SHAP feature-selection
step already used throughout the pipeline (prepare_xgboost_inputs +
train_xgboost_and_select_features), just fit on the full dataset instead
of a train/val split, since this is a global diagnostic rather than part
of the leakage-sensitive experiment pipeline.

(1)-A -- SHAP importance broken down by each of the 9 `is_*` deposit-type
groups: for records belonging to group g, rank features by mean(|SHAP|)
restricted to that subset. Checks whether the model actually leans on
geologically-plausible diagnostic minerals per deposit type (e.g.
carbonatite -> pyrochlore/fluorite, placer -> zircon/ilmenite), which the
reviewer doubts given only 1/9 groups (is_placer) survives the current
top-10 SHAP selection on the full node-feature vector.

(1)-B -- deposit-type entropy per region vs SPIRE's own per-region F1
(Exp1, result/gnn_inductive.json), to check whether regions with more
heterogeneous deposit-type composition are the ones where F1 is worse.
The 9 groups are not mutually exclusive (a record can carry >1 `is_*`
flag: 300 records carry 2, 55 carry 3, ...), so entropy is computed over
group *memberships* (each flag is one vote, plus a "none" bin for the 496
records with all 9 flags at 0), normalized by total votes in the region.

Output: result/deposit_type_shap.json, result/deposit_type_entropy_vs_f1.json
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "preprocessing"))

import numpy as np
import pandas as pd
from scipy.stats import pearsonr, spearmanr

from config import GNN_INDUCTIVE_METRICS_PATH, OUTPUT_PATH
from feature_engineering import prepare_xgboost_inputs, train_xgboost_and_select_features

IS_GROUP_COLS = [
    "is_carbonatite_system", "is_alkaline_intrusive", "is_mafic_ultramafic",
    "is_felsic_pegmatite", "is_metamorphic_metasomatic", "is_sedimentary",
    "is_placer", "is_supergene_lateritic", "is_unclassified",
]
TOP_N_PER_GROUP = 10


# ── (1)-A: SHAP importance by deposit-type group ────────────────────────────

def compute_shap_by_group(
    processed_df: pd.DataFrame,
    exclude_latlong: bool = False,
    exclude_region_country: bool = False,
) -> dict:
    """
    exclude_latlong=True drops Latitude/Longitude from X before fitting, so
    the ranking reflects purely mineralogical/lithological signal, uncontaminated
    by the model's much larger reliance on raw geographic coordinates (Lat+Long
    combined SHAP is 3.4-6.3x the best mineral feature in 8/9 groups when Lat/Long
    are present -- this variant asks what shows up once that shortcut is removed).

    exclude_region_country=True additionally drops the one-hot `Region_*` /
    `Country_*` columns. These are NOT curated geological features -- they're
    auto-generated by prepare_xgboost_inputs's generic categorical-encoding
    loop (any leftover object column not in NOTEBOOK_DROP_COLUMNS gets
    one-hot encoded), so they're a 2nd geographic shortcut alongside raw
    Lat/Long (confirmed: with Lat/Long removed, `Region_South and Central
    Asia` becomes the new #2/#3 driver in most groups). This variant checks
    whether mineral signal holds up once every geographic proxy is removed.

    Neither flag is a pipeline fix -- Lat/Long/Region/Country all stay as
    legitimate features in SPIRE/baselines elsewhere (unlike Comment 13's
    actual double-counting bug); these are diagnostic-only variants for
    Comment (1)-A.
    """
    graph_df, X, y = prepare_xgboost_inputs(processed_df, fit_idx=None,
                                             drop_coordinate_features=exclude_latlong)
    if exclude_region_country:
        drop_cols = [c for c in X.columns if c.startswith("Region_") or c.startswith("Country_")]
        X = X.drop(columns=drop_cols)
    model, shap_values, X_selected = train_xgboost_and_select_features(X, y, fit_idx=None)

    shap_array = np.asarray(shap_values)
    if shap_array.ndim == 3:
        shap_array = shap_array[-1]
    abs_shap = np.abs(shap_array)  # (N, F)

    feature_names = X.columns.tolist()
    is_group_local = graph_df.loc[X.index, IS_GROUP_COLS].reset_index(drop=True)

    overall_rank = abs_shap.mean(axis=0).argsort()[::-1][:TOP_N_PER_GROUP]
    result = {
        "overall_top": [
            {"feature": feature_names[i], "mean_abs_shap": float(abs_shap[:, i].mean())}
            for i in overall_rank
        ],
        "current_top10_selected": X_selected.columns.tolist(),
        "by_group": {},
    }

    for g in IS_GROUP_COLS:
        mask = is_group_local[g].to_numpy(dtype=bool)
        n = int(mask.sum())
        if n == 0:
            result["by_group"][g] = {"n": 0, "top_features": []}
            continue
        group_mean_abs = abs_shap[mask].mean(axis=0)
        top_idx = group_mean_abs.argsort()[::-1][:TOP_N_PER_GROUP]
        result["by_group"][g] = {
            "n": n,
            "top_features": [
                {"feature": feature_names[i], "mean_abs_shap": float(group_mean_abs[i])}
                for i in top_idx
            ],
        }

    return result


# ── (1)-B: deposit-type entropy per region vs SPIRE F1 ──────────────────────

def compute_region_entropy(processed_df: pd.DataFrame) -> dict:
    entropy_per_region = {}
    for region, rdf in processed_df.groupby("Region"):
        flags = rdf[IS_GROUP_COLS]
        counts = flags.sum(axis=0).to_dict()
        counts["none"] = int((flags.sum(axis=1) == 0).sum())
        total = sum(counts.values())
        if total == 0:
            entropy_per_region[region] = {"entropy": 0.0, "n": len(rdf), "counts": counts}
            continue
        probs = np.array([c / total for c in counts.values() if c > 0])
        entropy = float(-(probs * np.log2(probs)).sum())
        entropy_per_region[region] = {"entropy": entropy, "n": len(rdf), "counts": counts}
    return entropy_per_region


def load_spire_f1_per_region(metrics_path: str = GNN_INDUCTIVE_METRICS_PATH) -> dict:
    with open(metrics_path, encoding="utf-8") as f:
        d = json.load(f)
    f1_per_region: dict = {r: [] for r in d["regions"]}
    for run in d["runs"].values():
        for region, entry in run["per_region"].items():
            f1 = entry.get("test_metrics", {}).get("spire", {}).get("f1")
            if f1 is not None:
                f1_per_region[region].append(f1)
    return {r: float(np.mean(v)) for r, v in f1_per_region.items() if v}


def compute_entropy_vs_f1(processed_df: pd.DataFrame, metrics_path: str = GNN_INDUCTIVE_METRICS_PATH) -> dict:
    entropy = compute_region_entropy(processed_df)
    f1 = load_spire_f1_per_region(metrics_path)

    regions = sorted(set(entropy) & set(f1))
    ent_vals = [entropy[r]["entropy"] for r in regions]
    f1_vals = [f1[r] for r in regions]

    pearson_r, pearson_p = pearsonr(ent_vals, f1_vals)
    spearman_r, spearman_p = spearmanr(ent_vals, f1_vals)

    return {
        "per_region": {
            r: {"entropy": entropy[r]["entropy"], "n": entropy[r]["n"], "spire_f1": f1[r]}
            for r in regions
        },
        "pearson_r": float(pearson_r), "pearson_p": float(pearson_p),
        "spearman_r": float(spearman_r), "spearman_p": float(spearman_p),
    }


def main():
    print("Loading processed data...")
    processed_df = pd.read_excel(OUTPUT_PATH)

    Path("result").mkdir(exist_ok=True)

    print("\n[(1)-A] Computing SHAP importance by deposit-type group (Lat/Long included)...")
    shap_result = compute_shap_by_group(processed_df, exclude_latlong=False)
    with open("result/deposit_type_shap.json", "w", encoding="utf-8") as f:
        json.dump(shap_result, f, indent=2)
    print("  Saved -> result/deposit_type_shap.json")
    for g, info in shap_result["by_group"].items():
        top3 = ", ".join(t["feature"] for t in info["top_features"][:3])
        print(f"  {g:28s} n={info['n']:4d}  top3: {top3}")

    print("\n[(1)-A, no Lat/Long] Same, with Latitude/Longitude excluded from X "
          "(diagnostic-only -- shows purely mineralogical signal once the spatial "
          "shortcut is removed; SPIRE/baselines keep Lat/Long as-is elsewhere)...")
    shap_result_nolatlong = compute_shap_by_group(processed_df, exclude_latlong=True)
    with open("result/deposit_type_shap_no_latlong.json", "w", encoding="utf-8") as f:
        json.dump(shap_result_nolatlong, f, indent=2)
    print("  Saved -> result/deposit_type_shap_no_latlong.json")
    for g, info in shap_result_nolatlong["by_group"].items():
        top3 = ", ".join(t["feature"] for t in info["top_features"][:3])
        print(f"  {g:28s} n={info['n']:4d}  top3: {top3}")

    print("\n[(1)-A, no Lat/Long/Region/Country] Same, with Latitude/Longitude AND "
          "Region_*/Country_* one-hot columns excluded from X (checks whether mineral "
          "signal holds up once every geographic proxy, not just raw coordinates, is removed)...")
    shap_result_nogeo = compute_shap_by_group(processed_df, exclude_latlong=True,
                                               exclude_region_country=True)
    with open("result/deposit_type_shap_no_geo.json", "w", encoding="utf-8") as f:
        json.dump(shap_result_nogeo, f, indent=2)
    print("  Saved -> result/deposit_type_shap_no_geo.json")
    for g, info in shap_result_nogeo["by_group"].items():
        top3 = ", ".join(t["feature"] for t in info["top_features"][:3])
        print(f"  {g:28s} n={info['n']:4d}  top3: {top3}")

    print("\n[(1)-B] Computing deposit-type entropy vs SPIRE F1 per region...")
    entropy_result = compute_entropy_vs_f1(processed_df)
    with open("result/deposit_type_entropy_vs_f1.json", "w", encoding="utf-8") as f:
        json.dump(entropy_result, f, indent=2)
    print("  Saved -> result/deposit_type_entropy_vs_f1.json")
    for r, info in sorted(entropy_result["per_region"].items(), key=lambda kv: kv[1]["spire_f1"]):
        print(f"  {r:28s} entropy={info['entropy']:.3f}  spire_f1={info['spire_f1']:.3f}  n={info['n']}")
    print(f"\n  Pearson  r={entropy_result['pearson_r']:.3f}  p={entropy_result['pearson_p']:.3f}")
    print(f"  Spearman r={entropy_result['spearman_r']:.3f}  p={entropy_result['spearman_p']:.3f}")


if __name__ == "__main__":
    main()
